try:
    # 사용자에게 월을 입력받고, 정수로 변환한다.
    m = int(input('월(month) 입력 > '))

    # 월은 1부터 12 사이여야 한다.
    # 이 범위를 벗어나면 직접 예외를 발생시킨다.
    if not (1 <= m <= 12):
        raise Exception('1 ~ 12 사이의 정수를 입력하세요.')

# 예외가 발생하면 이 블록이 실행된다.
except Exception as e:
    print('예외 발생: {}'.format(e))

# 예외가 발생하지 않았을 때만 실행된다.
else:
    print('%d월: 잘 입력했습니다.' % m)

